MODE_FACTOR = {"精读": 1.35, "通读": 1.0, "选读": 0.55}


def allocate(slot_days, names):
    weights = []
    for n in names:
        pages = BOOKS[n][2]
        mode = BOOKS[n][3]
        weights.append(pages * MODE_FACTOR[mode])
    total = sum(weights)
    raw = [slot_days * w / total for w in weights]
    days = [max(2, int(round(x))) for x in raw]
    # 调整到刚好等于 slot_days
    while sum(days) < slot_days:
        i = max(range(len(days)), key=lambda k: raw[k] - days[k])
        days[i] += 1
    while sum(days) > slot_days:
        candidates = [k for k in range(len(days)) if days[k] > 2]
        i = min(candidates, key=lambda k: raw[k] - days[k])
        days[i] -= 1
    # 保证日均页数不超过 65；宁可让总天数略超三年，也不把史诗压成 3 天
    for i in range(len(days)):
        need = max(2, math.ceil(BOOKS[names[i]][2] / 65))
        if days[i] < need:
            days[i] = need
    return days


def main():
    books = []
    index = 0
    for stage, slot, slot_days, names in SLOTS:
        days_list = allocate(slot_days, names)
        for name, days in zip(names, days_list):
            index += 1
            author, part, pages, mode, background, prerequisite = BOOKS[name]
            books.append({
                "index": index,
                "title": name,
                "author": author,
                "part": part,
                "stage": stage,
                "slot": slot,
                "days": days,
                "pages": pages,
                "mode": mode,
                "background": background,
                "prerequisite": prerequisite,
            })
    missing = set(BOOKS) - {b["title"] for b in books}
    extra = {b["title"] for b in books} - set(BOOKS)
    if missing or extra:
        raise SystemExit(f"书名不匹配 missing={missing} extra={extra}")
    if len(books) != 100:
        raise SystemExit(f"数量错误：{len(books)}")
    total_days = sum(b["days"] for b in books)
    plan = {
        "schemaVersion": 1,
        "planName": "世界名著 100 本 · 三年阅读计划",
        "source": "https://mp.weixin.qq.com/s/5VCe36Y6JSMaSdUFemgslA",
        "startDate": "2026-11-19",
        "dailyPagesTarget": 35,
        "totalDays": total_days,
        "books": books,
    }
    out = Path(__file__).resolve().parents[1] / "app/src/main/assets/plan.json"
    out.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {out} books={len(books)} totalDays={total_days}")
    bad = [(b["title"], b["days"], b["pages"], round(b["pages"] / b["days"], 1)) for b in books if b["pages"] / b["days"] > 70]
    print("max pages/day:", max(round(b["pages"] / b["days"], 1) for b in books))
    print("over 70:", bad[:10])
    for b in books[:12]:
        print(b["index"], b["slot"], b["title"], b["days"], b["mode"], round(b["pages"] / b["days"], 1))


